CREATE OR REPLACE FUNCTION public.bloquear_desvinculacion_cliente()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if old.user_id is not null and new.user_id is null then
    raise exception 'Una cuenta ya vinculada no se puede desvincular.';
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.eliminar_cliente_completo(p_cliente_id bigint, p_modo text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_rol text := coalesce(public.get_my_role(), '');
  v_es_demo boolean;
  v_user_id uuid;
  v_ordenes_activas int;
begin
  select es_demo, user_id into v_es_demo, v_user_id
  from public.clientes
  where id = p_cliente_id;

  if not found then
    raise exception 'El cliente no existe.';
  end if;

  if (v_es_demo and v_rol <> 'demo') or (not v_es_demo and v_rol <> 'admin') then
    raise exception 'No tienes permiso para eliminar este cliente.';
  end if;

  if p_modo not in ('todo', 'conservar_historial') then
    raise exception 'Modo de eliminación inválido.';
  end if;

  select count(*) into v_ordenes_activas
  from public.ordenes o
  join public.vehiculos v on v.id = o.id_vehiculo
  where v.id_cliente = p_cliente_id
    and o.estado in ('Pendiente', 'En proceso');

  if v_ordenes_activas > 0 then
    raise exception 'Este cliente tiene % orden(es) pendiente(s) o en proceso. Complétalas o cancélalas antes de eliminar.', v_ordenes_activas;
  end if;

  if p_modo = 'todo' then
    delete from public.ordenes where id_vehiculo in (select id from public.vehiculos where id_cliente = p_cliente_id);
    delete from public.vehiculos where id_cliente = p_cliente_id;
  else
    update public.vehiculos set id_cliente = null where id_cliente = p_cliente_id;
  end if;

  delete from public.clientes where id = p_cliente_id;

  if v_user_id is not null then
    delete from auth.users where id = v_user_id;
  end if;
end;
$function$;

CREATE OR REPLACE FUNCTION public.enforce_es_demo_flag()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
begin
  if TG_OP = 'INSERT' then
    if public.get_my_role() = 'demo' then
      new.es_demo := true;
    else
      new.es_demo := false;
    end if;
  elsif TG_OP = 'UPDATE' then
    -- el flag es inmutable una vez creada la fila
    new.es_demo := old.es_demo;
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.fusionar_cliente_vinculado(p_cliente_destino_id bigint, p_usuario_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_cliente_origen_id bigint;
  v_direccion_origen text;
begin
  if coalesce(public.get_my_role(), '') <> 'admin' then
    raise exception 'Solo un administrador puede vincular o fusionar cuentas.';
  end if;

  select id into v_cliente_origen_id
  from public.clientes
  where user_id = p_usuario_id;

  if v_cliente_origen_id is null then
    update public.clientes set user_id = p_usuario_id where id = p_cliente_destino_id;
    return;
  end if;

  if v_cliente_origen_id = p_cliente_destino_id then
    raise exception 'Esa cuenta ya está vinculada a esta misma ficha.';
  end if;

  select direccion into v_direccion_origen from public.clientes where id = v_cliente_origen_id;

  -- Los datos que el cliente puso (fichaorigen, la de su cuenta autoregistrada)
  -- siempre tienen prioridad sobre lo que haya puesto el admin en el destino,
  -- igual que ya pasa con nombre/correo/telefono via el trigger de sincronización.
  if v_direccion_origen is not null and v_direccion_origen <> '' then
    update public.clientes set direccion = v_direccion_origen where id = p_cliente_destino_id;
  end if;

  update public.vehiculos set id_cliente = p_cliente_destino_id where id_cliente = v_cliente_origen_id;

  delete from public.clientes where id = v_cliente_origen_id;

  update public.clientes set user_id = p_usuario_id where id = p_cliente_destino_id;
end;
$function$;

CREATE OR REPLACE FUNCTION public.get_my_role()
 RETURNS text
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select rol from public.usuarios where id = auth.uid();
$function$;

CREATE OR REPLACE FUNCTION public.get_stats_publicas()
 RETURNS json
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select json_build_object(
    'clientes', (select count(*) from public.clientes where es_demo = false),
    'vehiculos', (select count(*) from public.vehiculos where es_demo = false),
    'ordenes_completadas', (
      select count(*) from public.ordenes
      where es_demo = false and estado = 'Completado'
    )
  );
$function$;

CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_telefono text;
  v_cliente_id bigint;
  v_nombre text;
  v_correo_verificado boolean;
begin
  v_nombre := coalesce(
    new.raw_user_meta_data->>'nombre',
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'name',
    ''
  );

  -- A1: nunca se toma el rol de la metadata del registro.
  insert into public.usuarios (id, nombre, correo, rol)
  values (new.id, v_nombre, new.email, 'cliente');

  v_telefono := coalesce(new.raw_user_meta_data->>'telefono', '');

  -- A2: solo se confía en el correo cuando lo verificó un proveedor OAuth.
  v_correo_verificado :=
    new.email_confirmed_at is not null
    and coalesce(new.raw_app_meta_data->>'provider', 'email') <> 'email';

  if v_correo_verificado then
    select id into v_cliente_id
    from public.clientes
    where user_id is null
      and es_demo = false
      and correo is not null
      and lower(correo) = lower(new.email)
    order by fecha_ingreso desc
    limit 1;
  end if;

  if v_cliente_id is not null then
    -- ya existía una ficha (creada por el admin) con ese mismo correo
    -- verificado: se vincula directamente.
    update public.clientes set user_id = new.id where id = v_cliente_id;
  else
    -- se crea una ficha nueva para que la persona aparezca en Clientes;
    -- si el taller ya tenía una ficha suya, el admin las fusiona.
    insert into public.clientes (nombre, correo, telefono, user_id, es_demo)
    values (v_nombre, new.email, v_telefono, new.id, false);
  end if;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.proteger_bloqueo_cliente()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.bloqueado is distinct from old.bloqueado
     and coalesce(public.get_my_role(), '') not in ('admin', 'demo') then
    raise exception 'No tienes permiso para cambiar el estado de bloqueo de este cliente.';
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.proteger_datos_cliente_vinculado()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  -- Si quien actualiza es admin y la fila ya estaba vinculada y sigue vinculada
  -- a la misma persona, no se permite tocar los datos de contacto: esos los
  -- controla únicamente el cliente desde su propio portal.
  if get_my_role() = 'admin'
     and old.user_id is not null
     and new.user_id is not distinct from old.user_id then
    if new.nombre is distinct from old.nombre
       or new.telefono is distinct from old.telefono
       or new.correo is distinct from old.correo
       or new.direccion is distinct from old.direccion then
      raise exception 'Este cliente ya está vinculado a una cuenta. Sus datos de contacto ahora los administra directamente desde su portal.';
    end if;
  end if;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.proteger_rol_usuario()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.rol is distinct from old.rol
     -- viene de la API (con JWT), no de una conexión directa a la base
     and nullif(current_setting('request.jwt.claims', true), '') is not null
     and coalesce(auth.jwt()->>'role', '') <> 'service_role'
     and coalesce(public.get_my_role(), '') <> 'admin' then
    raise exception 'No tienes permiso para cambiar el rol de este usuario.';
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.sincronizar_correo_usuario()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.email is distinct from old.email then
    update public.usuarios set correo = new.email where id = new.id;
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.sincronizar_datos_cliente_vinculado()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_nombre text;
  v_correo text;
  v_telefono text;
begin
  -- Se sincroniza únicamente cuando se está estableciendo o cambiando el
  -- vínculo a una cuenta (no en cada edición posterior). Los datos del
  -- cliente vinculado tienen prioridad sobre lo que haya puesto el admin.
  if new.user_id is not null
     and (old.user_id is null or old.user_id is distinct from new.user_id) then

    select u.nombre, u.correo, au.raw_user_meta_data->>'telefono'
      into v_nombre, v_correo, v_telefono
    from public.usuarios u
    join auth.users au on au.id = u.id
    where u.id = new.user_id;

    if v_nombre is not null and v_nombre <> '' then
      new.nombre := v_nombre;
    end if;

    if v_correo is not null and v_correo <> '' then
      new.correo := v_correo;
    end if;

    if v_telefono is not null and v_telefono <> '' then
      new.telefono := v_telefono;
    end if;
  end if;

  return new;
end;
$function$;

