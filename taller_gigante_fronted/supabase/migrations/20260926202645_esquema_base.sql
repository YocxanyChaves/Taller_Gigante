-- ===== TABLAS =====

create table public.clientes (
  id bigint generated by default as identity,
  nombre text not null,
  telefono text not null,
  correo text,
  direccion text,
  fecha_ingreso timestamp with time zone not null default now(),
  es_demo boolean not null default false,
  user_id uuid,
  bloqueado boolean not null default false
);

create table public.ordenes (
  id bigint generated by default as identity,
  id_vehiculo bigint not null,
  fecha_ingreso timestamp with time zone not null default now(),
  descripcion text,
  diagnostico text,
  estado text not null,
  costo_estimado text,
  costo_final text not null,
  fecha_entrega timestamp without time zone not null,
  es_demo boolean not null default false
);

create table public.solicitudes_vinculacion (
  id bigint generated always as identity,
  user_id uuid not null,
  telefono_ingresado text,
  cliente_id bigint,
  estado text not null default 'pendiente'::text,
  comentario_admin text,
  fecha_solicitud timestamp with time zone not null default now(),
  fecha_resolucion timestamp with time zone
);

create table public.usuarios (
  id uuid not null,
  nombre text not null,
  correo text not null,
  rol text not null default 'cliente'::text,
  fecha_registro timestamp with time zone not null default now()
);

create table public.vehiculos (
  id bigint generated by default as identity,
  id_cliente bigint,
  placa text not null,
  marca text,
  modelo text,
  "año" integer,
  color text,
  kilometraje text,
  es_demo boolean not null default false,
  ultima_revision_tecnica date
);

